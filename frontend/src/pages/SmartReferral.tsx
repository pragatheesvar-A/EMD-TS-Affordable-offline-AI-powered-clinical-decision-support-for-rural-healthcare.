import React, { useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Send, Download, CheckCircle2, ArrowRight } from 'lucide-react';
import { useApp } from '../context/AppContext';
import { Card, SectionTitle, Button, EmptyState, RiskBadge, Field, inputClass } from '../components/shared/ui';
import { referralForRisk } from '../lib/aiEngine';

export function SmartReferral() {
  const { patients, activePatientId, getScreeningsForPatient, getReferralsForPatient, addReferral } = useApp();
  const navigate = useNavigate();
  const patient = patients.find((p) => p.id === activePatientId);
  const [note, setNote] = useState('');
  const [generated, setGenerated] = useState(false);
  const [saved, setSaved] = useState(false);

  const screenings = patient ? getScreeningsForPatient(patient.id) : [];
  const latest = screenings[0];
  const existingReferrals = patient ? getReferralsForPatient(patient.id) : [];

  const details = useMemo(() => (latest ? referralForRisk(latest.riskLevel) : null), [latest]);

  function buildNote() {
    if (!patient || !latest || !details) return;
    const text = `SMART REFERRAL NOTE
--------------------------------------
Patient: ${patient.name} (${patient.id})
Age/Gender: ${patient.age} / ${patient.gender}
Village: ${patient.village}

Priority: ${latest.riskLevel}
Care Level: ${details.careLevel}
Suggested Specialist: ${details.specialist}
Reason: ${details.reason}

Vitals: HR ${latest.vitals.heartRate} BPM · SpO₂ ${latest.vitals.spo2}% · Temp ${latest.vitals.temperature}°C
AI Findings: ${latest.findings.map((f) => f.label).join('; ') || 'None'}

AI-assisted screening support. Clinician must confirm final diagnosis and treatment.
Generated by EMD-TS on ${new Date().toLocaleString()}.`;
    setNote(text);
    setGenerated(true);
  }

  async function handleSave() {
    if (!patient || !latest) return;
    await addReferral(patient.id, latest, note);
    setSaved(true);
  }

  function handleExport() {
    const blob = new Blob([note], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${patient?.id ?? 'referral'}-referral-note.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }

  if (!patient) {
    return (
      <div className="animate-fade-in">
        <SectionTitle title="Smart Referral" subtitle="Generate a structured referral note for the patient." />
        <Card>
          <EmptyState title="No patient selected" />
          <div className="flex justify-center mt-2">
            <Button onClick={() => navigate('/registration')}>Register a Patient</Button>
          </div>
        </Card>
      </div>
    );
  }

  if (!latest || !details) {
    return (
      <div className="animate-fade-in">
        <SectionTitle title="Smart Referral" subtitle={`${patient.name} (${patient.id})`} />
        <Card>
          <EmptyState title="No screening available" subtitle="Run AI Screening before generating a referral." />
          <div className="flex justify-center mt-2">
            <Button onClick={() => navigate('/screening')}>Go to AI Screening</Button>
          </div>
        </Card>
      </div>
    );
  }

  return (
    <div className="animate-fade-in">
      <SectionTitle title="Smart Referral" subtitle={`Structure the next step for ${patient.name} (${patient.id})`} />

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-4">
        <Card>
          <p className="text-xs text-slate-500 mb-1">Priority</p>
          <RiskBadge level={latest.riskLevel} />
        </Card>
        <Card>
          <p className="text-xs text-slate-500 mb-1">Care Level</p>
          <p className="text-sm font-semibold text-slate-900">{details.careLevel}</p>
        </Card>
        <Card>
          <p className="text-xs text-slate-500 mb-1">Suggested Specialist</p>
          <p className="text-sm font-semibold text-slate-900">{details.specialist}</p>
        </Card>
      </div>

      <Card className="mt-4">
        <p className="text-xs text-slate-500 mb-1">Reason</p>
        <p className="text-sm text-slate-800 mb-4">{details.reason}</p>

        <Field label="Structured referral note">
          <textarea
            className={`${inputClass} min-h-[220px] font-mono text-xs`}
            value={note}
            onChange={(e) => setNote(e.target.value)}
            placeholder='Click "Generate" to draft a structured referral note.'
          />
        </Field>

        <div className="flex flex-wrap gap-2 mt-4">
          <Button onClick={buildNote}>
            <Send size={15} /> Generate
          </Button>
          <Button variant="secondary" disabled={!generated || saved} onClick={handleSave}>
            {saved ? <><CheckCircle2 size={15}/> Saved</> : 'Save'}
          </Button>
          <Button variant="secondary" disabled={!note} onClick={handleExport}>
            <Download size={15} /> Print / Export
          </Button>
          <Button disabled={!generated} onClick={() => navigate('/doctor')}>
            Go to Doctor Dashboard <ArrowRight size={15} />
          </Button>
        </div>
        {saved && (
          <p className="text-xs text-emerald-600 mt-3">
            Referral saved and a <span className="font-semibold">REFERRAL_GENERATED</span> transaction was recorded
            on the local audit blockchain.
          </p>
        )}
        {generated && !saved && (
          <p className="text-xs text-amber-600 mt-3">
            Click <span className="font-semibold">Save</span> to record this referral before moving on.
          </p>
        )}
      </Card>

      {existingReferrals.length > 0 && (
        <Card className="mt-4">
          <h3 className="font-semibold text-slate-900 text-sm mb-3">Previous Referrals</h3>
          <div className="space-y-2">
            {existingReferrals.map((r) => (
              <div key={r.id} className="flex items-center justify-between border border-slate-100 rounded-lg px-3.5 py-2.5">
                <div>
                  <p className="text-sm text-slate-800 font-medium">{r.careLevel} — {r.specialist}</p>
                  <p className="text-xs text-slate-500">{new Date(r.createdAt).toLocaleString()}</p>
                </div>
                <RiskBadge level={r.priority} />
              </div>
            ))}
          </div>
        </Card>
      )}
    </div>
  );
}
